#!/usr/bin/env python3
"""Refreshes Sources/Models/CoverageAtlasData.swift, the copy of the coverage atlas built into the app.

The atlas itself is made on the website: publit-site/tools/coverage/make_atlas.py runs every week
(workflow "Abdeckung aktualisieren") on all Transitous sources worldwide and publishes
https://publit.eu/abdeckung/data/atlas.txt. The app downloads that file by itself
(CoverageAtlasStore), so new regions need no app update. This script only refreshes the built-in
fallback; the TestFlight workflow runs it before every build.

    python3 tools/coverage/make_atlas.py            # from publit.eu
    python3 tools/coverage/make_atlas.py --file atlas.txt

If the download fails the existing file is kept (exit code 0), so a build never breaks on it.
"""
import argparse, sys, urllib.request

URL = 'https://publit.eu/abdeckung/data/atlas.txt'
OUT = 'Sources/Models/CoverageAtlasData.swift'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--file')
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    try:
        text = open(a.file, encoding='utf-8').read() if a.file else \
            urllib.request.urlopen(urllib.request.Request(URL, headers={'User-Agent': 'publit-build'}), timeout=30).read().decode('utf-8')
    except Exception as e:
        print('atlas not refreshed:', e, file=sys.stderr); return
    lines = text.strip().split('\n')
    if not lines or not lines[0].startswith('D|'):
        print('atlas not refreshed: no date line', file=sys.stderr); return
    date = lines[0][2:].strip()
    areas = [l for l in lines[1:] if l.startswith('A|')]
    if len(areas) < 20 or any('"""' in l or '\\' in l for l in areas):
        print('atlas not refreshed: looks broken', file=sys.stderr); return
    swift = '''// Generated by tools/coverage/make_atlas.py from https://publit.eu/abdeckung/data/atlas.txt. Do not edit by hand.
// The built-in fallback: the app loads the newest atlas from publit.eu by itself (CoverageAtlasStore).
// One area per line: A|id|level (n none, s sparse, p partial)|gaps|name en|name de|map link (country or country/region)|shape
// shape: c<lat*1000>,<lon*1000>,<radius m> or p<ring>/<ring>... (zigzag varint deltas in 1/1000 degree, even-odd rule)

enum CoverageAtlasData {
    static let date = "%s"
    static let payload = """
%s
"""
}
''' % (date, '\n'.join(areas))
    open(a.out, 'w', encoding='utf-8').write(swift)
    print('atlas', date, len(areas), 'areas', len(swift), 'bytes', file=sys.stderr)


if __name__ == '__main__':
    main()
